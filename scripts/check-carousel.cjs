const { chromium } = require("playwright");
const path = require("path");
const { pathToFileURL } = require("url");
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe" });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.clock.install();
  await page.goto(pathToFileURL(path.join(process.cwd(), "index.html")).href);
  await page.locator("img").evaluateAll(images => images.forEach(image => image.loading = "eager"));
  await page.evaluate(() => Promise.all([...document.images].map(image => image.decode().catch(() => {}))));
  await page.locator("[data-carousel=next]").click();
  await page.locator('[data-slide="1"]').waitFor({ state: "visible" });
  if (!await page.locator("h1").isVisible()) throw Error("H1 disappeared during slide change");
  await page.locator('[data-carousel-index="0"]').click();
  await page.locator('[data-slide="0"]').waitFor({ state: "visible" });
  await page.locator(".hero").hover();
  await page.clock.fastForward(6500);
  if (!await page.locator('[data-slide="0"]').isVisible()) throw Error("Hover did not pause the carousel");
  await page.mouse.move(1200, 850);
  await page.evaluate(() => document.activeElement.blur());
  await page.clock.fastForward(6500);
  await page.locator('[data-slide="1"]').waitFor({ state: "visible" });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.clock.runFor(50);
  await page.clock.fastForward(6500);
  if (!await page.locator('[data-slide="1"]').isVisible()) throw Error("Reduced motion preference was ignored");
  if (errors.length) throw Error(errors.join("\n"));
  console.log("Carousel passed: navigation, visible H1, hover/focus pause, automatic switching, reduced motion and direct file loading.");
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
